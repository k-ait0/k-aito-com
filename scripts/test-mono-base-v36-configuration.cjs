"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const html=fs.readFileSync(path.join(__dirname,"../mono-base/cad-viewer.html"),"utf8");
assert.equal((html.match(/id="configuration-summary"/g)||[]).length,1);
assert.ok(html.includes('<label class="configuration-label" for="configuration-summary">'));
assert.ok(html.includes('readonly aria-describedby="configuration-explainer"'));
assert.ok(html.includes('id="configuration-copy-status" role="status" aria-live="polite"'));
assert.ok(html.includes("navigator.clipboard.writeText(summary.value)"));
assert.ok(html.includes("summary.select()"),"Must allow manual copy on denied clipboard permission");
assert.ok(html.includes("refreshConfiguration()}"),"Slider and mode state must refresh the summary");
assert.ok(html.includes("targetExplode=+e.target.value/100;refreshConfiguration()"),"Explode input must copy target percent, not animation lag");
const from=html.indexOf("function formatConfiguration(state){");
const to=html.indexOf("\nfunction refreshConfiguration(){",from);
assert.ok(from>=0&&to>from,"Pure formatter boundaries not found");
const code=html.slice(from,to);
const context=vm.createContext({});
vm.runInContext(code,context,{timeout:1000});
const format=state=>vm.runInContext("formatConfiguration("+JSON.stringify(state)+")",context,{timeout:1000});
const defaultState={mode:"solid",view:"iso",projection:"perspective",part:"fuselage",sweep:20,explodedPercent:0};
const baseline=format(defaultState);
assert.equal(baseline.split("\n").length,8);
assert.ok(baseline.includes("mode=SOLID"));
assert.ok(baseline.includes("view_preset=ISOMETRIC"));
assert.ok(baseline.includes("projection=PERSPECTIVE"));
assert.ok(baseline.includes("selected_part=FUSELAGE"));
assert.ok(baseline.includes("wing_sweep_deg=20"));
assert.ok(baseline.includes("exploded_view_percent=0"));
assert.ok(baseline.includes("not CAD, dimensions or simulation data"));
const changed=format({mode:"wire",view:"top",projection:"ortho",part:"wings",sweep:35,explodedPercent:60});
for(const value of ["mode=WIREFRAME","view_preset=TOP","projection=ORTHOGRAPHIC","selected_part=MAIN_WINGS","wing_sweep_deg=35","exploded_view_percent=60"]){
  assert.ok(changed.includes(value),"Updated configuration did not serialize "+value);
}
assert.notEqual(changed,baseline);
assert.equal(format(defaultState),baseline,"Reset must reproduce baseline settings");
assert.ok(!baseline.includes("undefined"));
assert.ok(!changed.includes("undefined"));
const staticText=html.match(/<textarea\b[^>]*id="configuration-summary"[^>]*>([\s\S]*?)<\/textarea>/)[1];
assert.equal(staticText.trim(),baseline,"Static accessible fallback and runtime default must match");
console.log("PASS MONO BASE v3.6: accessible copyable concept settings, six state fields, deterministic reset, clipboard fallback");
